"""Writes the hardware bring-up data: the vector-register and program
images and power-up screen for the bring-up build of gpt_top, and the MCU
header mcu/src/bringup_data.h.

Usage (from the repository root, after python model/export.py):
    python tools/make_bringup.py

The bring-up runs the model's output-layer MATVEC (instruction 52) and
HALT for BOS at position 0, from the register file the full program
leaves before that instruction, and checks the scores against Python.
"""

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "model"))

from isa import A_OUT, F_ALT, VR_X, decode  # noqa: E402

MEM = REPO / "fpga" / "mem"
VECTORS = REPO / "fpga" / "sim" / "vectors" / "prefix_empty"
PROG_IN = MEM / "prog.mem"
VREG_IN = VECTORS / "pos0_vreg.mem"
SCORES_IN = VECTORS / "pos0_scores.mem"
HEADER_OUT = REPO / "mcu" / "src" / "bringup_data.h"

OUT_INSTR = 52
VREG_WORDS = 1024
N_SCORES = 27
LETTER = 26
POS = 0

COLS, ROWS, CELLS = 40, 15, 1024
SCREEN: list[str] = [
    "  iCE40 Transformer Accelerator",
    "  E155 Final Project",
    "",
    "  FPGA configured, waiting for MCU",
    "",
    "  pixel clock: 12 MHz oscillator,",
    "  PLL 25.125 MHz",
]

# ------------------------------------------------------------------------------
# Inputs
# ------------------------------------------------------------------------------


def read_lines(path: Path) -> list[str]:
    """Read a generated .mem file, failing with a hint if it is missing.

    Args:
        path: File written by model/export.py.

    Returns:
        Non-empty lines without whitespace.
    """
    if not path.exists():
        sys.exit(f"{path} not found; run python model/export.py first")
    return [line.strip() for line in path.read_text().splitlines()
            if line.strip()]


def signed16(value: int) -> int:
    """Interpret a 16-bit value as two's complement.

    Args:
        value: Unsigned 16-bit value.

    Returns:
        Signed value.
    """
    return value - (1 << 16) if value & 0x8000 else value


# ------------------------------------------------------------------------------
# Outputs
# ------------------------------------------------------------------------------


def screen_cells() -> list[int]:
    """Text-buffer bytes for SCREEN, all white.

    Returns:
        1,024 cell bytes, cell = row x 40 + col.
    """
    assert len(SCREEN) <= ROWS
    cells = [0] * CELLS
    for r, text in enumerate(SCREEN):
        assert len(text) <= COLS, f"row {r} is longer than {COLS}"
        for c, ch in enumerate(text):
            cells[r * COLS + c] = ord(ch) & 0x7F
    return cells


def header(prog: list[int], scores: list[int]) -> str:
    """C header with the bring-up program and expected scores.

    Args:
        prog: Instruction words.
        scores: Expected int16 scores.

    Returns:
        Header text.
    """
    prog_bytes = [w >> (8 * k) & 0xFF for w in prog for k in range(5, -1, -1)]
    prog_text = ", ".join(f"0x{b:02x}" for b in prog_bytes)
    score_rows = [", ".join(str(s) for s in scores[i:i + 9])
                  for i in range(0, len(scores), 9)]
    return ("// bringup_data.h\n"
            "// Generated by tools/make_bringup.py; do not edit\n\n"
            "#ifndef BRINGUP_DATA_H\n#define BRINGUP_DATA_H\n\n"
            "#include <stdint.h>\n\n"
            f"#define BRINGUP_LETTER {LETTER}\n"
            f"#define BRINGUP_POS {POS}\n"
            f"#define BRINGUP_NINSTR {len(prog)}\n\n"
            f"static const uint8_t bringup_prog[{len(prog_bytes)}] = {{\n"
            f"    {prog_text}\n}};\n\n"
            f"static const int16_t bringup_scores[{len(scores)}] = {{\n    "
            + ",\n    ".join(score_rows) + "\n};\n\n"
            "#endif // BRINGUP_DATA_H\n")


def main() -> None:
    """Check the inputs and write the four bring-up files."""
    prog_lines = read_lines(PROG_IN)
    vreg_lines = read_lines(VREG_IN)
    score_lines = read_lines(SCORES_IN)
    assert len(vreg_lines) % VREG_WORDS == 0
    assert len(score_lines) == N_SCORES

    out_word = int(prog_lines[OUT_INSTR], 16)
    fields = decode(out_word)
    assert fields["op"] == "MATVEC", fields
    assert fields["flags"] >> F_ALT & 1, fields
    assert fields["base"] == A_OUT, fields
    assert fields["rows"] == 32 and fields["cols"] == 64, fields
    assert fields["src"] == VR_X, fields
    prog = [out_word, 0]

    (MEM / "bringup_vreg.mem").write_text(
        "".join(f"{line}\n" for line in vreg_lines[-VREG_WORDS:]))
    (MEM / "bringup_prog.mem").write_text(
        "".join(f"{w:012x}\n" for w in prog))
    (MEM / "bringup_text.mem").write_text(
        "".join(f"{b:02x}\n" for b in screen_cells()))
    HEADER_OUT.write_text(
        header(prog, [signed16(int(s, 16)) for s in score_lines]))
    print(f"wrote bringup_vreg.mem, bringup_prog.mem, bringup_text.mem in "
          f"{MEM} and {HEADER_OUT}")


if __name__ == "__main__":
    main()
